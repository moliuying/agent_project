@Injectable()
export class CookingQaService {
  private tips: CookingTip[] = COOKING_TIPS;
  private knowledge: KnowledgeEntry[] = COOKING_KNOWLEDGE;

  ask(question: string): AskResponse {
    const normalizedQuestion = question.toLowerCase().trim();

    let bestMatch: KnowledgeEntry | null = null;
    let maxMatches = 0;

    for (const entry of this.knowledge) {
      let matches = 0;
      for (const keyword of entry.keywords) {
        if (normalizedQuestion.includes(keyword.toLowerCase())) {
          matches++;
        }
      }
      if (matches > maxMatches) {
        maxMatches = matches;
        bestMatch = entry;
      }
    }

    if (bestMatch && maxMatches > 0) {
      const relatedTips = this.tips.filter(tip => bestMatch!.tipIds.includes(tip.id));
      return {
        answer: bestMatch.answer,
        relatedTips,
        relatedTechniques: bestMatch.techniques,
      };
    }

    return {
      answer: DEFAULT_ANSWER,
      relatedTips: this.tips.slice(0, 3),
      relatedTechniques: ['温度控制', '食材预处理', '操作时机'],
    };
  }

  getSuggestedQuestions(): string[] {
    return [
      '鱼怎么煎不粘锅？',
      '炒菜总是出水怎么办？',
      '蛋糕为什么塌了？',
      '牛肉怎么炒才嫩？',
      '米饭怎么煮才好吃？',
      '鱼汤怎么煮才奶白？',
      '青菜怎么炒保持翠绿？',
    ];
  }

  getAllCookingTips(): CookingTip[] {
    return this.tips;
  }
}
